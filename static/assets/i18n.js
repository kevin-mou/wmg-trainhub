const LANG_KEY = "trainhub.lang";
let currentLang = localStorage.getItem(LANG_KEY) === "en" ? "en" : "zh";

export function getLang() {
  return currentLang;
}

export function setLang(lang) {
  currentLang = lang === "en" ? "en" : "zh";
  localStorage.setItem(LANG_KEY, currentLang);
  document.documentElement.lang = currentLang === "en" ? "en" : "zh-CN";
}

function lookup(dict, path) {
  return path.split(".").reduce((node, part) => (node == null ? undefined : node[part]), dict);
}

export function t(key, vars = {}) {
  let value = lookup(dictionaries[currentLang], key);
  if (value === undefined) value = lookup(dictionaries.zh, key);
  if (value === undefined) return key;
  if (typeof value !== "string") return key;
  return value.replace(/\{(\w+)\}/g, (match, name) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match
  );
}

export function locale() {
  return currentLang === "en" ? "en-US" : "zh-CN";
}
